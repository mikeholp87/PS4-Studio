// Precompiles theme.schema.json into plain JavaScript so the app never calls `new Function`/eval
// at runtime (the app's Content-Security-Policy forbids 'unsafe-eval'). Run: pnpm gen
import Ajv from 'ajv'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const schemaPath = new URL('../theme.schema.json', import.meta.url)
const outJs = new URL('../src/validator.generated.js', import.meta.url)
const outDts = new URL('../src/validator.generated.d.ts', import.meta.url)

export function build() {
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8'))
  const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true } })
  const validate = ajv.compile(schema)
  const header = '// @ts-nocheck\n// GENERATED by scripts/gen-validator.mjs from theme.schema.json. Do not edit; run `pnpm gen`.\n'
  let code = standaloneCode(ajv, validate)
  // Ajv's ESM output still require()s one tiny runtime helper, which a browser cannot do. Inline it
  // (same algorithm as ajv/dist/runtime/ucs2length: counts Unicode code points).
  const req = 'require("ajv/dist/runtime/ucs2length").default'
  if (!code.includes(req)) throw new Error('unexpected ajv output: ucs2length require not found')
  code = code.replace(req, 'ucs2length')
  if (/\brequire\(/.test(code)) throw new Error('generated validator still contains require()')
  const helper =
    'function ucs2length(str){const len=str.length;let length=0,pos=0,value;while(pos<len){length++;value=str.charCodeAt(pos++);if(value>=0xd800&&value<=0xdbff&&pos<len){value=str.charCodeAt(pos);if((value&0xfc00)===0xdc00)pos++}}return length}\n'
  return header + helper + code
}

export const dts = `// GENERATED. See validator.generated.js
export interface ValidationIssue { instancePath: string; message?: string }
declare const validate: ((data: unknown) => boolean) & { errors?: ValidationIssue[] | null }
export default validate
`

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outJs, build())
  writeFileSync(outDts, dts)
  console.log('wrote src/validator.generated.js')
}
